export const translate = (language: string | null | undefined, key: TranslationKey): string => {
  const normalized = normalizeLanguage(language);
  return translations[normalized][key] ?? translations.en[key] ?? translations.vi[key] ?? key;
};

export const getMultiLangText = (
  language: string | null | undefined,
  texts: { vi: string; en: string; ja?: string; ko?: string; zh?: string; fr?: string; de?: string; es?: string }
): string => {
  const lang = normalizeLanguage(language);
  return texts[lang] || texts.en || texts.vi;
};

export const getMultiLangArray = <T>(
  language: string | null | undefined,
  arrays: { vi: T[]; en: T[]; ja?: T[]; ko?: T[]; zh?: T[]; fr?: T[]; de?: T[]; es?: T[] }
): T[] => {
  const lang = normalizeLanguage(language);
  return arrays[lang] || arrays.en || arrays.vi;
};

export const translateCategory = (language: string | null | undefined, name?: string): string => {
  if (!name) return translate(language, 'category.study');
  const lower = name.toLowerCase().trim();
  if (lower.includes('họp') || lower.includes('meet')) return translate(language, 'category.meeting');
  if (lower.includes('học') || lower.includes('stud')) return translate(language, 'category.study');
  if (lower.includes('công việc') || lower.includes('work')) return translate(language, 'category.work');
  if (lower.includes('cá nhân') || lower.includes('person')) return translate(language, 'category.personal');
  if (lower.includes('thói quen') || lower.includes('habit')) return translate(language, 'category.habit');
  if (lower.includes('deadline')) return translate(language, 'category.deadline');
  if (lower.includes('cần làm') || lower.includes('task') || lower.includes('to-do')) return translate(language, 'category.task');
  if (lower.includes('ý tưởng') || lower.includes('idea')) return getMultiLangText(language, { vi: 'Ý tưởng', en: 'Idea', ja: 'アイデア', ko: '아이디어', zh: '想法', fr: 'Idée', de: 'Idee', es: 'Idea' });
  if (lower.includes('quan trọng') || lower.includes('important')) return getMultiLangText(language, { vi: 'Quan trọng', en: 'Important', ja: '重要', ko: '중요', zh: '重要', fr: 'Important', de: 'Wichtig', es: 'Importante' });
  if (lower.includes('ghi chú') || lower.includes('note')) return getMultiLangText(language, { vi: 'Ghi chú', en: 'Note', ja: 'メモ', ko: '노트', zh: '笔记', fr: 'Note', de: 'Notiz', es: 'Nota' });
  if (lower.includes('sức khỏe') || lower.includes('health')) return getMultiLangText(language, { vi: 'Sức khỏe', en: 'Health', ja: '健康', ko: '건강', zh: '健康', fr: 'Santé', de: 'Gesundheit', es: 'Salud' });
  if (lower.includes('khác') || lower.includes('other')) return getMultiLangText(language, { vi: 'Khác', en: 'Other', ja: 'その他', ko: '기타', zh: '其他', fr: 'Autre', de: 'Andere', es: 'Otro' });
  return name;
};

export const translateRelativeTime = (language: string | null | undefined, timeStr?: string): string => {
  if (!timeStr) return '';
  const numMatches = timeStr.match(/\d+/);
  const num = numMatches ? numMatches[0] : '';

  if (timeStr === 'Vừa xong' || timeStr === 'Just now') {
    return getMultiLangText(language, {
      vi: 'Vừa xong',
      en: 'Just now',
      ja: 'たった今',
      ko: '방금 전',
      zh: '刚刚',
      fr: 'À l\'instant',
      de: 'Gerade eben',
      es: 'Justo ahora',
    });
  }

  if (timeStr === 'Hôm nay' || timeStr === 'Today') {
    return getMultiLangText(language, {
      vi: 'Hôm nay',
      en: 'Today',
      ja: '今日',
      ko: '오늘',
      zh: '今天',
      fr: 'Aujourd\'hui',
      de: 'Heute',
      es: 'Hoy',
    });
  }

  if (timeStr === 'Hôm qua' || timeStr === 'Yesterday') {
    return getMultiLangText(language, {
      vi: 'Hôm qua',
      en: 'Yesterday',
      ja: '昨日',
      ko: '어제',
      zh: '昨天',
      fr: 'Hier',
      de: 'Gestern',
      es: 'Ayer',
    });
  }

  if (timeStr.includes('ngày') || timeStr.includes('day')) {
    if (!num) return timeStr;
    return getMultiLangText(language, {
      vi: `${num} ngày trước`,
      en: `${num} days ago`,
      ja: `${num}日前`,
      ko: `${num}일 전`,
      zh: `${num}天前`,
      fr: `il y a ${num} jours`,
      de: `vor ${num} Tagen`,
      es: `hace ${num} días`,
    });
  }

  if (timeStr.includes('giờ') || timeStr.includes('hour') || timeStr.includes('hr')) {
    if (!num) return timeStr;
    return getMultiLangText(language, {
      vi: `${num} giờ trước`,
      en: `${num} hours ago`,
      ja: `${num}時間前`,
      ko: `${num}시간 전`,
      zh: `${num}小时前`,
      fr: `il y a ${num}h`,
      de: `vor ${num} Std.`,
      es: `hace ${num} h`,
    });
  }

  if (timeStr.includes('phút') || timeStr.includes('min')) {
    if (!num) return timeStr;
    return getMultiLangText(language, {
      vi: `${num} phút trước`,
      en: `${num} mins ago`,
      ja: `${num}分前`,
      ko: `${num}分前`,
      zh: `${num}分钟前`,
      fr: `il y a ${num} min`,
      de: `vor ${num} Min.`,
      es: `hace ${num} min`,
    });
  }

  return timeStr;
};






